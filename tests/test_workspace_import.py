def _edges(upstream, downstream):
    from laurelin.core.models import LineageEdge

    return [LineageEdge(upstream_dataset=upstream, downstream_dataset=downstream,
                        transform_name="derive")]


@pytest.fixture()
def target(tmp_path, make_store):
    workspace = Workspace.init(tmp_path / "dst", name="dst")
    return workspace, make_store(workspace)


def _roundtrip(source, target, tmp_path, options=None, **export_kwargs):
    src_ws, src_store = source
    dst_ws, dst_store = target
    archive = tmp_path / f"export-{uuid.uuid4().hex[:6]}.tar"
    export_workspace(src_ws, src_store, archive, ExportOptions(**export_kwargs))
    report = import_workspace(archive, dst_ws, dst_store, options or ImportOptions())
    return archive, report


