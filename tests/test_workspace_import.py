# --------------------------------------------------------------------------- helpers

def _names(raw: bytes) -> list[str]:
    with tarfile.open(fileobj=io.BytesIO(raw), mode="r|*") as tar:
        return [m.name for m in tar]


def _member(raw: bytes, name: str) -> str:
    with tarfile.open(fileobj=io.BytesIO(raw), mode="r|*") as tar:
        for member in tar:
            if member.name == name:
                return tar.extractfile(member).read().decode()
    raise AssertionError(f"no member {name!r}")


def _repack(archive, tmp_path, *, replace=None, extra=(), drop=(), retrailer=True):
    """Rewrite an archive, recomputing TRAILER.json unless told not to.

    Recomputed by default so a test exercises the defence it is about instead
    of stopping at the digest check — which would make every one of these pass
    for the same reason and prove only that one thing.
    """
    import hashlib

    replace = replace or {}
    kept: list[tuple[str, bytes]] = []
    with tarfile.open(archive, mode="r|*") as src:
        for member in src:
            if member.name in drop:
                continue
            payload = src.extractfile(member).read()
            kept.append((member.name, replace.get(member.name, payload)))
    for name, payload in extra:
        kept.insert(1, (name, payload))

    if retrailer:
        digests = {
            name: {"sha256": hashlib.sha256(body).hexdigest(), "bytes": len(body)}
            for name, body in kept if name != "TRAILER.json"
        }
        trailer = json.dumps({
            "members": digests, "member_count": len(digests),
            "total_bytes": sum(d["bytes"] for d in digests.values()),
        }).encode()
        kept = [(n, trailer if n == "TRAILER.json" else b) for n, b in kept]

    out = io.BytesIO()
    with tarfile.open(fileobj=out, mode="w") as tar:
        for name, body in kept:
            info = tarfile.TarInfo(name)
            info.size = len(body)
            info.mode = 0o600
            tar.addfile(info, io.BytesIO(body))
    out.seek(0)
    return out


def _rows_of(archive, table):
    return [
        json.loads(line)
        for line in _member(archive.read_bytes(), f"tables/{table}.jsonl").splitlines()
        if line.strip()
    ]


def _as_jsonl(rows):
    return b"".join(json.dumps(r).encode() + b"\n" for r in rows)


