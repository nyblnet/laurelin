def test_a_failed_import_leaves_no_half_populated_workspace(
    source, target, tmp_path, monkeypatch
):
    """Every metadata row lands in one transaction, and parts written before
    the failure are unreferenced garbage rather than a registered version."""
    from laurelin.export import reader

    src_ws, src_store = source
    dst_ws, dst_store = target
    archive = tmp_path / "export.tar"
    export_workspace(src_ws, src_store, archive, ExportOptions())

    real, calls = reader._write_part, {"n": 0}

    def explode(storage, key, spilled):
        # Fail on the *second* part, so the first one is genuinely on disk when
        # the rollback happens. A failure before any write proves nothing.
        calls["n"] += 1
        if calls["n"] > 1:
            raise OSError("storage went away mid-import")
        return real(storage, key, spilled)

    monkeypatch.setattr(reader, "_write_part", explode)

    with pytest.raises(OSError, match="storage went away"):
        import_workspace(archive, dst_ws, dst_store, ImportOptions())

    assert dst_store.list_datasets() == []
    assert dst_store.list_markings() == []
    assert list(dst_ws.data_dir.rglob("*.parquet")) == []
    assert list(dst_ws.root.glob(".laurelin-import-*")) == []


