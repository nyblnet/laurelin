def test_a_table_member_that_declares_more_than_the_ceiling_is_refused(
    source, target, tmp_path
):
    """Measured: a 514 KiB gzipped archive declaring a 512 MiB audit_log member
    took the importer from 172 MiB to 4794 MiB of RSS and then reported a
    successful import. The declared size is in the header, so it costs nothing
    to refuse before reading."""
    from laurelin.export.reader import MAX_TABLE_MEMBER_BYTES

    src_ws, src_store = source
    dst_ws, dst_store = target
    archive = tmp_path / "good.tar"
    export_workspace(src_ws, src_store, archive, ExportOptions())

    bomb = tmp_path / "bomb.tar.gz"
    size = MAX_TABLE_MEMBER_BYTES + 1

    class _Filler(io.RawIOBase):
        def readable(self):
            return True

        def read(self, n=-1):
            return b"\n" * min(n if n and n > 0 else 65536, 1 << 20)

    with tarfile.open(bomb, "w:gz") as out, tarfile.open(archive, "r|*") as src:
        for member in src:
            payload = src.extractfile(member).read()
            info = tarfile.TarInfo(member.name)
            info.size = len(payload)
            out.addfile(info, io.BytesIO(payload))
            if member.name == MANIFEST_MEMBER:
                info = tarfile.TarInfo("tables/audit_log.jsonl")
                info.size = size
                out.addfile(info, _Filler())

    assert bomb.stat().st_size < (2 << 20), "the bomb must be cheap to build"
    with pytest.raises(ImportRefused, match="ceiling"):
        import_workspace(bomb, dst_ws, dst_store, ImportOptions())


