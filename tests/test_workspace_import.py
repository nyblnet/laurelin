@pytest.mark.parametrize(
    "name, kind",
    [
        ("../../etc/passwd", tarfile.REGTYPE),
        ("/etc/passwd", tarfile.REGTYPE),
        ("tables/../../etc/passwd", tarfile.REGTYPE),
        ("ontology/evil.yml", tarfile.SYMTYPE),
        ("pipelines/evil.py", tarfile.LNKTYPE),
        ("etc/passwd", tarfile.REGTYPE),
    ],
)
def test_a_tar_member_escaping_the_workspace_is_refused(
    source, target, tmp_path, name, kind
):
    """`filter="data"` is a default that differs across the supported range, so
    member names are validated independently of it."""
    src_ws, src_store = source
    dst_ws, dst_store = target
    good = tmp_path / "good.tar"
    export_workspace(src_ws, src_store, good, ExportOptions())

    hostile = io.BytesIO()
    with tarfile.open(fileobj=hostile, mode="w") as out:
        with tarfile.open(good, mode="r") as src:
            manifest = src.getmember(MANIFEST_MEMBER)
            out.addfile(manifest, src.extractfile(manifest))
        info = tarfile.TarInfo(name)
        info.type = kind
        if kind == tarfile.REGTYPE:
            info.size = 5
            out.addfile(info, io.BytesIO(b"pwned"))
        else:
            info.linkname = "../../etc/passwd"
            out.addfile(info)
    hostile.seek(0)

    with pytest.raises(ImportRefused):
        import_workspace(hostile, dst_ws, dst_store, ImportOptions())
    assert not (dst_ws.root / "etc").exists()


